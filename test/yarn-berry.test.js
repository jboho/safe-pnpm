// Runs `yarn <args>` through the bash, zsh or fish wrapper in a Berry project, with
// a stub docker that tells the containers apart by their arguments (fetch has
// --mode=skip-build, the audit runs `npm audit`, the build has --immutable)
// and records, per container, its arguments and the .yarnrc.yml files it can
// see. Fetch writes node_modules, package.json and yarn.lock like a real
// resolve. Host yarn and corepack are stubs that log their calls.
//
// opts.args       yarn arguments (default ["install"])
// opts.pkg        project package.json object (default PKG)
// opts.yarnrc     project .yarnrc.yml text, or null for none (default YARNRC)
// opts.homeYarnrc ~/.yarnrc.yml text, or null for none (default HOME_YARNRC)
// opts.lock       project yarn.lock text, or null for none (default LOCK)
// opts.phase1Lock yarn.lock the fetch writes (default PHASE1_LOCK)
// opts.workspace  root workspaces ["packages/*"] with member packages/a, run
//                 from packages/a; the fetch gives every member a node_modules
// opts.member     the member folder's name in place of "a"
// opts.memberPkg  packages/a/package.json text (default a plain manifest)
// opts.patches    put .yarn/patches/ms.patch in the project; "mixed" adds a
//                 notes.txt and a link.patch symlink to a file outside it;
//                 "linked" makes .yarn a symlink to a folder outside it
// opts.reserved   put a package.json in the project's .corepack, .safe-home
//                 and .safe-store folders, which the sandbox uses itself
// opts.mac       a `uname` that reports Darwin arm64
// opts.noNode     a `node` that fails as if it were not installed
// opts.osvApi     install the real malware scanner against this OSV API
// opts.auditFails the audit container exits 1
// opts.dockerInfo canned `docker info --format` answers
// opts.env        extra environment
// opts.pre        shell code run before the wrapper files are sourced
function berry(shell, opts = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "safe-berry-"));
  const bin = path.join(root, "bin");
  const proj = path.join(root, "proj");
  const log = path.join(root, "log");
  for (const d of [bin, proj, log, path.join(root, ".safe-pnpm")])
    fs.mkdirSync(d);
  fs.copyFileSync(
    path.join(ASSETS, "link-check.js"),
    path.join(root, ".safe-pnpm", "link-check.js"),
  );
  if (opts.osvApi) {
    fs.copyFileSync(
      path.join(ASSETS, "malware-scan.js"),
      path.join(root, ".safe-pnpm", "malware-scan.js"),
    );
  }
  if (opts.mac) {
    fs.writeFileSync(
      path.join(bin, "uname"),
      '#!/bin/sh\nif [ "$1" = -m ]; then echo arm64; else echo Darwin; fi\n',
      { mode: 0o755 },
    );
  }
  for (const tool of ["yarn", "corepack"]) {
    fs.writeFileSync(
      path.join(bin, tool),
      `#!/bin/sh\necho "${tool} $*" >> "${log}/host"\nexit 0\n`,
      { mode: 0o755 },
    );
  }
  if (opts.noNode) {
    fs.writeFileSync(
      path.join(bin, "node"),
      '#!/bin/sh\necho "node: command not found" >&2\nexit 127\n',
      { mode: 0o755 },
    );
  }

  const pkg = opts.pkg ?? PKG;
  fs.writeFileSync(
    path.join(proj, "package.json"),
    JSON.stringify(
      opts.workspace ? { ...pkg, workspaces: ["packages/*"] } : pkg,
    ),
  );
  const yarnrc = opts.yarnrc === undefined ? YARNRC : opts.yarnrc;
  if (yarnrc !== null) fs.writeFileSync(path.join(proj, ".yarnrc.yml"), yarnrc);
  const lock = opts.lock === undefined ? LOCK : opts.lock;
  if (lock !== null) fs.writeFileSync(path.join(proj, "yarn.lock"), lock);
  const homeYarnrc =
    opts.homeYarnrc === undefined ? HOME_YARNRC : opts.homeYarnrc;
  if (homeYarnrc !== null)
    fs.writeFileSync(path.join(root, ".yarnrc.yml"), homeYarnrc);
  if (opts.patches) {
    const yarnDir =
      opts.patches === "linked"
        ? path.join(root, "outside-yarn")
        : path.join(proj, ".yarn");
    fs.mkdirSync(path.join(yarnDir, "patches"), { recursive: true });
    fs.writeFileSync(
      path.join(yarnDir, "patches", "ms.patch"),
      "--- a/index.js\n",
    );
    if (opts.patches === "linked")
      fs.symlinkSync(yarnDir, path.join(proj, ".yarn"));
    if (opts.patches === "mixed") {
      fs.writeFileSync(path.join(proj, ".yarn", "patches", "notes.txt"), "x\n");
      fs.writeFileSync(path.join(root, "outside.patch"), "--- a/x\n");
      fs.symlinkSync(
        path.join(root, "outside.patch"),
        path.join(proj, ".yarn", "patches", "link.patch"),
      );
    }
  }
  if (opts.reserved) {
    for (const d of [
      ".corepack/v1/yarn/4.18.1",
      ".safe-home",
      ".safe-store/x",
    ]) {
      fs.mkdirSync(path.join(proj, d), { recursive: true });
      fs.writeFileSync(path.join(proj, d, "package.json"), "{}");
    }
  }
  let cwd = proj;
  if (opts.workspace) {
    cwd = path.join(proj, "packages", opts.member ?? "a");
    fs.mkdirSync(cwd, { recursive: true });
    fs.writeFileSync(
      path.join(cwd, "package.json"),
      opts.memberPkg ?? JSON.stringify({ name: "a", version: "1.0.0" }),
    );
  }
  fs.writeFileSync(
    path.join(log, "phase1-lock"),
    opts.phase1Lock ?? PHASE1_LOCK,
  );
  fs.writeFileSync(
    path.join(log, "phase1-pkg"),
    JSON.stringify(
      opts.workspace
        ? { ...PHASE1_PKG, workspaces: ["packages/*"] }
        : PHASE1_PKG,
    ),
  );

  const stub = `#!/usr/bin/env bash
${infoStubSh(opts.dockerInfo)}
[ "$1" = run ] || exit 0
src=""; prev=""
for a in "$@"; do
  case "$prev" in -v) src="\${a%%:/app}" ;; esac
  prev="$a"
done
case " $* " in
  *" npm audit "*) phase=audit ;;
  *" --mode=skip-build "*) phase=fetch ;;
  *" --immutable "*) phase=build ;;
  *) phase=other ;;
esac
echo "$phase" >> "${log}/order"
echo "$@" > "${log}/$phase.args"
printf '%s\\n' "$@" > "${log}/$phase.argv"
[ -f "$src/.yarnrc.yml" ] && cp "$src/.yarnrc.yml" "${log}/$phase.yarnrc"
[ -f "$src/.safe-home/.yarnrc.yml" ] && cp "$src/.safe-home/.yarnrc.yml" "${log}/$phase.home"
[ -d "$src/.yarn/patches" ] && ls -A "$src/.yarn/patches" > "${log}/$phase.patches"
find "$src/.corepack" "$src/.safe-home" "$src/.safe-store" -name package.json > "${log}/$phase.reserved" 2>/dev/null
if [ "$phase" = fetch ]; then
  mkdir -p "$src/node_modules/ms"
  echo "module.exports=1" > "$src/node_modules/ms/index.js"
  cp "${log}/phase1-pkg" "$src/package.json"
  cp "${log}/phase1-lock" "$src/yarn.lock"
  if [ -d "$src/packages/a" ]; then
    echo '{"name":"a","version":"1.0.0","dependencies":{"ms":"^2.1.3"}}' > "$src/packages/a/package.json"
  fi
  for m in "$src"/packages/*/; do [ -d "$m" ] && mkdir -p "$m/node_modules/x"; done
fi
${opts.auditFails ? '[ "$phase" = audit ] && { echo "1 high severity advisory" >&2; exit 1; }' : ""}
exit 0
`;
  fs.writeFileSync(path.join(bin, "docker"), stub, { mode: 0o755 });

  const words = (opts.args ?? ["install"]).map((a) => `'${a}'`).join(" ");
  const sources =
    shell === "fish"
      ? ["_safe_pkg_prescan.fish", "yarn-wrapper.fish"]
      : ["_safe_pkg_shared.sh", "yarn-wrapper.sh"];
  const script = `${opts.pre ?? ""}${sources.map((f) => `source "${path.join(ASSETS, f)}"; `).join("")}cd "${cwd}"; yarn ${words} </dev/null`;
  const env = {
    ...process.env,
    PATH: `${bin}:${process.env.PATH}`,
    HOME: root,
    NPM_TOKEN: "SECRET-TOKEN-VALUE",
    NODE_AUTH_TOKEN: "",
    SAFE_PNPM_OSV_API: opts.osvApi ?? "",
    npm_config_userconfig: "",
    NPM_CONFIG_USERCONFIG: "",
    ...opts.env,
  };
  for (const k of [
    "SAFE_PNPM_STRICT",
    "SAFE_PNPM_OSV_STRICT",
    "SAFE_PNPM_BUILD_NETWORK",
  ]) {
    if (!(opts.env && k in opts.env)) delete env[k];
  }
  const argv =
    shell === "fish" ? ["--no-config", "-c", script] : ["-c", script];
  // A wrapper that loops forever fails the test instead of hanging the suite.
  const r = spawnSync(shell, argv, { stdio: "pipe", env, timeout: 120000 });

  const at = (f) => path.join(log, f);
  const read = (f) => fs.readFileSync(at(f), "utf8");
  const order = fs.existsSync(at("order"))
    ? read("order").trim().split("\n")
    : [];
  const host = fs.existsSync(at("host")) ? read("host").trim().split("\n") : [];
  return {
    root,
    proj,
    order,
    host,
    read,
    has: (f) => fs.existsSync(at(f)),
    status: r.status,
    err: r.stderr.toString(),
    done: () => fs.rmSync(root, { recursive: true, force: true }),
  };
}

const withRun = (shell, opts, fn) => {
  const run = berry(shell, opts);
  try {
    fn(run);
  } finally {
    run.done();
  }
};

