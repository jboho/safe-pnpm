const { test, before, after } = require("node:test");
const assert = require("node:assert/strict");
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { infoStubSh } = require("./helpers/docker-info-stub");
const { IMAGE, hasDocker, buildPwshImage } = require("./helpers/pwsh-image");

// The sandbox runs Yarn 1. Given a Yarn 2+ (Berry) project it ignores the
// Berry lockfile, resolves every version again and writes a Yarn 1 lockfile
// that the copy-back puts over the project's own, so yarn installs in a Berry
// project are refused before phase 1, strict mode or not.
const ASSETS = path.join(__dirname, "..", "assets");
const REFUSAL = "the wrapper supports Yarn 1 projects only";

const available = (sh) =>
  spawnSync(sh, ["--version"], { stdio: "pipe" }).status === 0;

const BERRY_LOCK =
  '# This file is generated by running "yarn install" inside your project.\n' +
  "# Manual changes might be lost - proceed with caution!\n\n" +
  "__metadata:\n  version: 8\n  cacheKey: 10c0\n";
const V1_LOCK =
  "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n" +
  '# yarn lockfile v1\n\n\nis-odd@3.0.1:\n  version "3.0.1"\n';
const pkg = (extra) =>
  JSON.stringify({ name: "x", version: "1.0.0", ...extra }, null, 2);

// [file, contents, yarn args, what the refusal names after the project dir]
const REFUSED = [
  ["yarn.lock", BERRY_LOCK, ["install"], "/yarn.lock is a Yarn 2+ lockfile"],
  [".yarnrc.yml", "nodeLinker: node-modules\n", ["install"], "/.yarnrc.yml is a Yarn 2+ settings file"],
  [
    "package.json",
    pkg({ packageManager: "yarn@4.5.3" }),
    ["install"],
    "/package.json sets packageManager to yarn@4.5.3",
  ],
  [
    "package.json",
    pkg({ packageManager: "yarn@3.6.0+sha512.0123abcd" }),
    ["install"],
    "/package.json sets packageManager to yarn@3.6.0",
  ],
  ["yarn.lock", BERRY_LOCK, ["add", "is-odd"], "/yarn.lock is a Yarn 2+ lockfile"],
];

// [file, contents, yarn args]
const KEPT = [
  ["yarn.lock", V1_LOCK, ["install"]],
  [".yarnrc", 'registry "https://r.example/"\n', ["install"]],
  ["package.json", pkg({ packageManager: "yarn@1.22.22" }), ["install"]],
];

const label = (file, contents, args) =>
  `yarn ${args.join(" ")} with ${file} ${JSON.stringify(contents.split("\n").find((l) => /__metadata|packageManager|yarnrc|nodeLinker|lockfile v1|registry/.test(l)) || "")}`;

// A docker whose `info` succeeds and whose `run` is logged and fails, so a
// logged run shows the wrapper got as far as phase 1.
function project(file, contents) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "safe-pnpm-berry-"));
  const bin = path.join(root, "bin");
  const proj = path.join(root, "proj");
  fs.mkdirSync(bin);
  fs.mkdirSync(proj);
  fs.writeFileSync(
    path.join(bin, "docker"),
    `#!/bin/sh\n${infoStubSh()}\necho "$@" >> "${root}/docker.log"\nexit 1\n`,
    { mode: 0o755 },
  );
  fs.writeFileSync(path.join(proj, "package.json"), pkg({}));
  fs.writeFileSync(path.join(proj, file), contents);
  const runs = () => {
    try {
      return fs
        .readFileSync(path.join(root, "docker.log"), "utf8")
        .split("\n")
        .filter((l) => l.startsWith("run "));
    } catch {
      return [];
    }
  };
  return { root, bin, proj, runs };
}

function runShell(shell, mgr, args, { root, bin, proj }, pre = "") {
  const words = args.map((a) => `'${a}'`).join(" ");
  const script =
    shell === "fish"
      ? `source "${path.join(ASSETS, "_safe_pkg_prescan.fish")}"; ${pre}source "${path.join(ASSETS, `${mgr}-wrapper.fish`)}"; cd "${proj}"; ${mgr} ${words} </dev/null`
      : `source "${path.join(ASSETS, "_safe_pkg_shared.sh")}"; source "${path.join(ASSETS, `${mgr}-wrapper.sh`)}"; cd "${proj}"; ${mgr} ${words} </dev/null`;
  const argv =
    shell === "fish" ? ["--no-config", "-c", script] : ["-c", script];
  const env = {
    ...process.env,
    PATH: `${bin}:${process.env.PATH}`,
    HOME: root,
  };
  delete env.SAFE_PNPM_OSV_STRICT;
  delete env.SAFE_PNPM_STRICT;
  const r = spawnSync(shell, argv, { stdio: "pipe", env });
  return { status: r.status, err: r.stderr.toString() };
}

for (const shell of ["bash", "zsh", "fish"]) {
  const skip = available(shell) ? false : `${shell} not available`;
  for (const [file, contents, args, named] of REFUSED) {
    test(`${shell}: ${label(file, contents, args)} is refused before phase 1`, {
      skip,
    }, () => {
      const p = project(file, contents);
      try {
        const { status, err } = runShell(shell, "yarn", args, p);
        assert.equal(status, 1, err);
        assert.ok(
          err.includes(`${path.basename(p.proj)}${named}, and ${REFUSAL}`),
          err,
        );
        assert.match(
          err,
          new RegExp(`without the safety checks: command yarn ${args.join(" ")}`),
        );
        assert.deepEqual(p.runs(), []);
      } finally {
        fs.rmSync(p.root, { recursive: true, force: true });
      }
    });
  }
  for (const [file, contents, args] of KEPT) {
    test(`${shell}: ${label(file, contents, args)} reaches phase 1`, {
      skip,
    }, () => {
      const p = project(file, contents);
      try {
        const { err } = runShell(shell, "yarn", args, p);
        assert.ok(!err.includes(REFUSAL), err);
        assert.equal(p.runs().length, 1, err);
      } finally {
        fs.rmSync(p.root, { recursive: true, force: true });
      }
    });
  }
  // A Berry yarn.lock is yarn's business: npm and pnpm installs go ahead.
  for (const mgr of ["npm", "pnpm"]) {
    test(`${shell}: ${mgr} install with a Berry yarn.lock reaches phase 1`, {
      skip,
    }, () => {
      const p = project("yarn.lock", BERRY_LOCK);
      try {
        const { err } = runShell(shell, mgr, ["install"], p);
        assert.ok(!err.includes(REFUSAL), err);
        assert.equal(p.runs().length, 1, err);
      } finally {
        fs.rmSync(p.root, { recursive: true, force: true });
      }
    });
  }
}

test("bash: the refusal holds under SAFE_PNPM_OSV_STRICT=1 too", {
  skip: available("bash") ? false : "bash not available",
}, () => {
  const p = project("yarn.lock", BERRY_LOCK);
  try {
    const script = `source "${path.join(ASSETS, "_safe_pkg_shared.sh")}"; source "${path.join(ASSETS, "yarn-wrapper.sh")}"; cd "${p.proj}"; yarn install </dev/null`;
    const r = spawnSync("bash", ["-c", script], {
      stdio: "pipe",
      env: {
        ...process.env,
        PATH: `${p.bin}:${process.env.PATH}`,
        HOME: p.root,
        SAFE_PNPM_OSV_STRICT: "1",
      },
    });
    const err = r.stderr.toString();
    assert.equal(r.status, 1, err);
    assert.ok(err.includes(REFUSAL), err);
    assert.deepEqual(p.runs(), []);
  } finally {
    fs.rmSync(p.root, { recursive: true, force: true });
  }
});

test("fish: an out-of-date _safe_pkg_prescan.fish refuses instead of skipping the check", {
  skip: available("fish") ? false : "fish not available",
}, () => {
  const p = project("yarn.lock", V1_LOCK);
  try {
    const { status, err } = runShell(
      "fish",
      "yarn",
      ["install"],
      p,
      "functions -e _safe_pkg_yarn_berry; ",
    );
    assert.equal(status, 1, err);
    assert.match(err, /_safe_pkg_prescan\.fish is missing or out of date/);
    assert.deepEqual(p.runs(), []);
  } finally {
    fs.rmSync(p.root, { recursive: true, force: true });
  }
});

// PowerShell: every case in one Linux pwsh container, one project dir each.
const skipPs1 = hasDocker ? false : "docker not available";
let tmp;
before(() => {
  tmp = fs.mkdtempSync(path.join(os.tmpdir(), "safe-pnpm-ps1berry-"));
  if (hasDocker) buildPwshImage();
});
after(() => {
  if (tmp) fs.rmSync(tmp, { recursive: true, force: true });
});

let ps1Result;
function runPs1Cases() {
  if (ps1Result) return ps1Result;
  const root = fs.mkdtempSync(path.join(tmp, "w-"));
  const bin = path.join(root, "bin");
  const safe = path.join(root, "home", ".safe-pnpm");
  for (const d of [bin, safe]) fs.mkdirSync(d, { recursive: true });
  for (const f of [
    "_safe_pkg_shared.ps1",
    "npm-wrapper.ps1",
    "yarn-wrapper.ps1",
  ]) {
    fs.copyFileSync(path.join(ASSETS, f), path.join(safe, f));
  }
  fs.writeFileSync(
    path.join(bin, "docker"),
    `#!/bin/sh\n${infoStubSh()}\necho "$CASE $*" >> /w/docker.log\nexit 1\n`,
    { mode: 0o755 },
  );
  const cases = [
    ...REFUSED.map(([file, contents, args]) => ["yarn", file, contents, args]),
    ...KEPT.map(([file, contents, args]) => ["yarn", file, contents, args]),
    ["npm", "yarn.lock", BERRY_LOCK, ["install"]],
    ["stale", "yarn.lock", V1_LOCK, ["install"]],
  ].map(([mgr, file, contents, args], i) => {
    const proj = path.join(root, `p${i}`);
    fs.mkdirSync(proj);
    fs.writeFileSync(path.join(proj, "package.json"), pkg({}));
    fs.writeFileSync(path.join(proj, file), contents);
    return { id: `c${i}`, mgr, dir: `/w/p${i}`, args };
  });
  fs.writeFileSync(path.join(root, "cases.json"), JSON.stringify(cases));
  const script = [
    "$env:PATH = '/w/bin:' + $env:PATH",
    "Remove-Item env:SAFE_PNPM_OSV_STRICT -ErrorAction SilentlyContinue",
    "Remove-Item env:SAFE_PNPM_STRICT -ErrorAction SilentlyContinue",
    '. "$HOME/.safe-pnpm/npm-wrapper.ps1"; . "$HOME/.safe-pnpm/yarn-wrapper.ps1"',
    "foreach ($c in (Get-Content /w/cases.json -Raw | ConvertFrom-Json)) {",
    "  Set-Location $c.dir; $env:CASE = $c.id; $global:LASTEXITCODE = 0; $a = @($c.args)",
    "  if ($c.mgr -eq 'stale') {",
    "    $saved = (Get-Item function:_Safe_Pkg_Yarn_Berry).ScriptBlock",
    "    Remove-Item function:_Safe_Pkg_Yarn_Berry",
    "    $out = (& { try { yarn @a } catch { \"THROWN: $($_.Exception.Message)\" } } *>&1 | Out-String) -replace '\\r?\\n', ' '",
    "    Set-Item function:global:_Safe_Pkg_Yarn_Berry -Value $saved",
    "  } else {",
    "    $out = (& { try { & $c.mgr @a } catch { \"THROWN: $($_.Exception.Message)\" } } *>&1 | Out-String) -replace '\\r?\\n', ' '",
    "  }",
    '  "RUN|$($c.id)|$LASTEXITCODE|$out"',
    "}",
  ].join("\n");
  const r = spawnSync(
    "docker",
    [
      "run",
      "--rm",
      "--platform",
      "linux/amd64",
      "--user",
      `${process.getuid()}:${process.getgid()}`,
      "-e",
      "HOME=/w/home",
      "-v",
      `${root}:/w`,
      IMAGE,
      "pwsh",
      "-NoProfile",
      "-Command",
      script,
    ],
    { encoding: "utf8" },
  );
  const lines = (r.stdout || "").split("\n");
  const get = (id) => {
    const line = lines.find((l) => l.startsWith(`RUN|${id}|`));
    return line ? line.split("|").slice(2) : undefined;
  };
  let dockerLog = "";
  try {
    dockerLog = fs.readFileSync(path.join(root, "docker.log"), "utf8");
  } catch {}
  const runLines = (id) =>
    dockerLog.split("\n").filter((l) => l.startsWith(`${id} run `));
  ps1Result = { get, runLines, out: r.stdout + r.stderr };
  return ps1Result;
}

REFUSED.forEach(([file, contents, args, named], i) => {
  test(`ps1: ${label(file, contents, args)} is refused before phase 1`, {
    skip: skipPs1,
  }, () => {
    const { get, runLines, out } = runPs1Cases();
    const r = get(`c${i}`);
    assert.ok(r, out);
    const text = r.slice(1).join("|");
    assert.equal(r[0], "1", text);
    assert.ok(text.includes(`/w/p${i}${named}, and ${REFUSAL}`), text);
    assert.match(
      text,
      new RegExp(`without the safety checks: yarn\\.cmd ${args.join(" ")}`),
    );
    assert.equal(runLines(`c${i}`).length, 0);
  });
});

KEPT.forEach(([file, contents, args], j) => {
  const i = REFUSED.length + j;
  test(`ps1: ${label(file, contents, args)} reaches phase 1`, {
    skip: skipPs1,
  }, () => {
    const { get, runLines, out } = runPs1Cases();
    const r = get(`c${i}`);
    assert.ok(r, out);
    assert.ok(!r.slice(1).join("|").includes(REFUSAL), r.join("|"));
    assert.equal(runLines(`c${i}`).length, 1, r.join("|"));
  });
});

test("ps1: npm install with a Berry yarn.lock reaches phase 1", {
  skip: skipPs1,
}, () => {
  const { get, runLines, out } = runPs1Cases();
  const i = REFUSED.length + KEPT.length;
  const r = get(`c${i}`);
  assert.ok(r, out);
  assert.ok(!r.slice(1).join("|").includes(REFUSAL), r.join("|"));
  assert.equal(runLines(`c${i}`).length, 1, r.join("|"));
});

test("ps1: a _safe_pkg_shared.ps1 without the Yarn Berry check refuses to install", {
  skip: skipPs1,
}, () => {
  const { get, runLines, out } = runPs1Cases();
  const i = REFUSED.length + KEPT.length + 1;
  const r = get(`c${i}`);
  assert.ok(r, out);
  assert.equal(r[0], "1", r.join("|"));
  assert.match(
    r.slice(1).join("|"),
    /_safe_pkg_shared\.ps1 is missing or out of date/,
  );
  assert.equal(runLines(`c${i}`).length, 0);
});
